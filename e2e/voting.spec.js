import { expect, test } from '@playwright/test'

test('complete demo flow, reload privacy, session lock and reset', async ({ page }) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Kenali calonnya.')
  await page.getByRole('button', { name: 'Panduan', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Memilih itu mudah.')
  await page.getByRole('button', { name: 'Mulai memilih' }).click()
  await page.getByLabel('Kode akses').fill('salah')
  await page.getByLabel('Kode akses').press('Enter')
  await expect(page.getByRole('alert')).toHaveText('Kode belum sesuai. Gunakan DEMO-2026 untuk mencoba.')
  await page.getByLabel('Kode akses').fill(' demo-2026 ')
  await page.getByLabel('Kode akses').press('Enter')
  await expect(page.getByRole('button', { name: 'Lanjutkan' })).toBeDisabled()
  await page.getByRole('button', { name: 'Lihat profil Aditya Pratama' }).click()
  await expect(page.getByText('Forum aspirasi siswa setiap bulan.')).toBeVisible()
  await page.getByRole('button', { name: 'Pilih Aditya Pratama' }).click()
  await expect(page.getByRole('radio', { name: 'Pilih Aditya Pratama' })).toBeChecked()
  await page.getByRole('button', { name: 'Lanjutkan' }).click()
  await expect(page.getByRole('button', { name: 'Kirim suara demo' })).toBeDisabled()
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Ubah pilihan' }).click()
  await page.getByRole('radio', { name: 'Pilih Nadia Azzahra' }).check()
  await page.getByRole('button', { name: 'Lanjutkan' }).click()
  await expect(page.getByRole('checkbox')).not.toBeChecked()
  await page.getByRole('checkbox').check()
  await page.reload()
  await expect(page.getByRole('checkbox')).not.toBeChecked()
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Kirim suara demo' }).click()
  await expect(page.getByText('PM-2026-DEMO')).toBeVisible()
  await expect(page.getByText('Nadia Azzahra')).toHaveCount(0)
  const snapshot = await page.evaluate(() => JSON.parse(sessionStorage.getItem('pemilos-spenthree-demo-v1')))
  expect(snapshot).toEqual({ screen: 'success', authorized: true, voted: true, selected: null })
  await page.reload()
  await expect(page.getByText('PM-2026-DEMO')).toBeVisible()
  await page.getByRole('button', { name: 'Kembali ke beranda' }).click()
  await page.getByRole('button', { name: 'Bukti memilih', exact: true }).click()
  await expect(page.getByText('PM-2026-DEMO')).toBeVisible()
  await page.getByRole('button', { name: 'Ulangi demo' }).click()
  await page.getByRole('button', { name: 'Mulai memilih' }).click()
  await expect(page.getByLabel('Kode akses')).toHaveValue('')
  await page.getByRole('button', { name: 'Isi kode demo otomatis' }).click()
  await expect(page.getByLabel('Kode akses')).toHaveValue('DEMO-2026')
  expect(errors).toEqual([])
})

test('fits narrow screens and respects the device theme', async ({ page }, testInfo) => {
  await page.goto('/')
  const dark = testInfo.project.name === 'mobile-dark'
  expect(await page.locator('body').evaluate((element) => getComputedStyle(element).color)).toBe(dark ? 'rgb(237, 247, 241)' : 'rgb(36, 59, 50)')
  for (const width of [320, 375, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const box = await page.locator('.app-shell').boundingBox()
    expect(box.width).toBeLessThanOrEqual(410)
  }
  await page.setViewportSize({ width: 320, height: 900 })
  await page.getByRole('button', { name: 'Mulai memilih' }).click()
  await page.getByRole('button', { name: 'Isi kode demo otomatis' }).click()
  await page.getByRole('button', { name: 'Buka surat suara' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
